"""The frontend parser fixture is the real ``EnvironmentService`` output (UI-3 S2).

``frontend/src/test/fixtures/environment-snapshots.json`` is generated by
``tools/ui2/synthetic_environment.py`` from the production ``snapshot()``/``derive_options()``
on top of a synthetic profile CLI. If the legacy environment contract changes, this test fails
until the fixture (and so the frontend parser tests) is regenerated and re-checked.
"""

from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path
from types import ModuleType

ROOT = Path(__file__).resolve().parents[1]


def _module() -> ModuleType:
    path = ROOT / "tools" / "ui2" / "synthetic_environment.py"
    spec = importlib.util.spec_from_file_location("ui2_synthetic_environment", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_frontend_fixture_matches_the_real_environment_service() -> None:
    module = _module()
    assert module.FIXTURE.read_text(encoding="utf-8") == module.render()


def test_fixture_covers_the_s2_states_without_real_values() -> None:
    data = json.loads(_module().render())
    assert data["no_profile_parameter"]["active_profile"] is None  # several built: no choice
    assert data["vulkan_not_built"]["active_profile"] is None
    assert data["cpu"]["options"]["asr"] == []  # no installed model: zero candidates
    assert [o["id"] for o in data["cuda"]["options"]["asr"]] == ["faster-whisper"]
    assert data["intel"]["errors"]  # partial: one CLI call failed
    text = json.dumps(data)
    for marker in ("\\\\", "C:", "/home/", "/Users/", "hf_"):
        assert marker not in text
